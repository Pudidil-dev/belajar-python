// Pixel fonts. FC: mixed-case caption/label font (cap height 7, descenders 2).
// FS: micro font for axes and tags (5-row caps, row 6 = descender). FT: 9-row bold title.
// ============================================================================
function mkFont(h, defs, spaceW, base) {
  const g = {};
  for (const ch in defs) {
    const rows = defs[ch].split('/');
    const w = rows[0].length, off = (base && base[ch]) || 0;
    const bits = new Array(h).fill(0);
    rows.forEach((r, i) => { let v = 0; for (let k = 0; k < r.length; k++) if (r[k] === '#') v |= 1 << k; if (i + off < h) bits[i + off] = v; });
    g[ch] = { w, bits };
  }
  g[' '] = { w: spaceW, bits: new Array(h).fill(0) };
  return { h, g };
}
