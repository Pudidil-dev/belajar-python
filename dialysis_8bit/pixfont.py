def _compile(table, height):
    out = {}
    for ch, rows in table.items():
        assert len(rows) == height, (ch, len(rows))
        w = len(rows[0])
        assert all(len(r) == w for r in rows), ch
        out[ch] = np.array([[c == "#" for c in r] for r in rows], dtype=bool)
    return out


class Font:
    def __init__(self, glyphs, height, spacing=1, space_w=None, fallback_upper=False):
        self.g = glyphs
        self.h = height
        self.sp = spacing
        self.fallback_upper = fallback_upper

    def glyph(self, ch):
        if ch in self.g:
            return self.g[ch]
        if self.fallback_upper and ch.upper() in self.g:
            return self.g[ch.upper()]
        return self.g[" "]

    def width(self, text):
        if not text:
            return 0
        return sum(self.glyph(c).shape[1] + self.sp for c in text) - self.sp

    def mask(self, text, scale=1):
        """Boolean mask of the rendered string (h x w)."""
        w = max(1, self.width(text))
        m = np.zeros((self.h, w), dtype=bool)
        x = 0
        for c in text:
            g = self.glyph(c)
            m[:, x:x + g.shape[1]] |= g
            x += g.shape[1] + self.sp
        if scale != 1:
            m = m.repeat(scale, 0).repeat(scale, 1)
        return m


