FONTS = {'5x7': (_F57, 7), '3x5': (_F35, 5)}
_cache = {}


def _glyph(ch, font):
    table, h = FONTS[font]
    rows = table.get(ch.upper(), table.get('?', table[' ']))
    return np.array([[c == '#' for c in r] for r in rows], bool)


def text_bitmap(s, font='5x7', spacing=1, scale=1):
    key = (s, font, spacing, scale)
    if key in _cache:
        return _cache[key]
    glyphs = [_glyph(c, font) for c in s]
    h = FONTS[font][1]
    w = sum(g.shape[1] for g in glyphs) + spacing * max(len(glyphs) - 1, 0)
    out = np.zeros((h, max(w, 1)), bool)
    x = 0
    for g in glyphs:
        out[:, x:x + g.shape[1]] = g
        x += g.shape[1] + spacing
    if scale > 1:
        out = np.kron(out, np.ones((scale, scale), bool)).astype(bool)
    _cache[key] = out
    return out


def text_size(s, font='5x7', scale=1):
    b = text_bitmap(s, font, scale=scale)
    return b.shape[1], b.shape[0]


def text_mask(s, x, y, font='5x7', anchor='lt', scale=1):
    """Mask of the string. anchor: 'l'/'m'/'r' horizontally + 't'/'m'/'b' vertically."""
    b = text_bitmap(s, font, scale=scale)
    h, w = b.shape
    ax = {'l': 0, 'm': w // 2, 'r': w}[anchor[0]]
    ay = {'t': 0, 'm': h // 2, 'b': h}[anchor[1]]
    return gfx.Mask(int(round(x)) - ax, int(round(y)) - ay, b).clip()


def draw_text(buf, s, x, y, color, font='5x7', anchor='lt', outline=OUTLINE, shadow=None, scale=1):
    mk = text_mask(s, x, y, font, anchor, scale)
    if mk.empty():
        return mk
    if shadow is not None:
        gfx.fill(buf, mk.dilate(scale, diag=True).shifted(scale, scale), shadow)
    if outline is not None:
        gfx.fill(buf, mk.dilate(scale, diag=True), outline)
    gfx.fill(buf, mk, color)
    return mk


# ------------------------------------------------------------------ 7-segment LCD digits (5 wide x 9 tall)
_SEG = {  # a b c d e f g
    '0': 'abcdef', '1': 'bc', '2': 'abdeg', '3': 'abcdg', '4': 'bcfg', '5': 'acdfg', '6': 'acdefg',
    '7': 'abc', '8': 'abcdefg', '9': 'abcdfg', 'E': 'adefg', 'n': 'ceg', 'd': 'bcdeg', '-': 'g', ' ': '',
    'r': 'eg', 'o': 'cdeg', 'P': 'abefg', 'L': 'def', 'U': 'bcdef', 'S': 'acdfg', 'A': 'abcefg', 't': 'defg',
}


def _seg_pixels(seg):
    return {
        'a': [(1, 0), (2, 0), (3, 0)], 'g': [(1, 4), (2, 4), (3, 4)], 'd': [(1, 8), (2, 8), (3, 8)],
        'f': [(0, 1), (0, 2), (0, 3)], 'b': [(4, 1), (4, 2), (4, 3)],
        'e': [(0, 5), (0, 6), (0, 7)], 'c': [(4, 5), (4, 6), (4, 7)],
    }[seg]


def draw_lcd(buf, s, x, y, on, ghost):
    """Draw a string of 7-segment digits; unlit segments in `ghost` (real LCD look)."""
    for i, ch in enumerate(s):
        lit = _SEG.get(ch, '')
        for seg in 'abcdefg':
            col = on if seg in lit else ghost
            if col is None:
                continue
            for (px, py) in _seg_pixels(seg):
                xx, yy = x + i * 7 + px, y + py
                if 0 <= xx < gfx.W and 0 <= yy < gfx.H:
                    buf[yy, xx] = col
