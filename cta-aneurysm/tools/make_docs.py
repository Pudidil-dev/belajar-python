#!/usr/bin/env python3
"""Build the production package's text documents from the sources the film is made of, so they cannot drift:
the shot list (镜头表.md), each scene file's header comment, the cue sheet (build/cues.json, from render.py --cues) and the
text log (build/textlog.json). Writes docs/storyboard.md, docs/timeline.md, docs/prompts.md, docs/captions.md,
docs/cue_sheet.md.

  python3 tools/make_docs.py
"""
import json, re
from collections import defaultdict
from pathlib import Path

R = Path(__file__).resolve().parent.parent
D = R / 'docs'; D.mkdir(exist_ok=True)
shot = (R / '镜头表.md').read_text()
cues = json.loads((R / 'build/cues.json').read_text())
textlog = json.loads((R / 'build/textlog.json').read_text()) if (R / 'build/textlog.json').exists() else {}

def table(md, first):
    rows, on = [], False
    for ln in md.splitlines():
        if ln.startswith('| ' + first): on = True; continue
        if on and ln.startswith('|---'): continue
        if on and ln.startswith('|'): rows.append([c.strip() for c in ln.strip().strip('|').split('|')])
        elif on: break
    return rows
SHOTS = table(shot, '场 | 时间段')
LABELS = {r[0]: r for r in table(shot, '场 | Label')}
CAM = {'停': 'hold', '缓推': 'slow push', '拉远': 'pull out', '横移': 'pan / track', '快推': 'fast push (accent)', '切': 'cut'}
ids = re.findall(r"'(s\d\d_[a-z0-9]+)'", (R / 'engine/film.js').read_text())
def header(sid):
    src = (R / 'engine/scenes' / f'{sid}.js').read_text().splitlines()
    out = []
    for ln in src:
        if ln.startswith('//'): out.append(ln[2:].strip())
        else: break
    return ' '.join(out)
def xin(sid):
    m = re.search(r'xin:\s*([\d.]+)', (R / 'engine/scenes' / f'{sid}.js').read_text()); return float(m.group(1)) if m else 0.0
by_scene = defaultdict(list)
for c in cues['cues']: by_scene[c['scene']].append(c)
ACT = [(0, 'ACT 1 — THE HIDDEN SHAPE'), (5, 'ACT 2 — ELECTRONS GAIN ENERGY'), (10, 'ACT 3 — X-RAYS ARE PRODUCED'), (15, 'ACT 4 — CONTRAST REACHES THE ARTERIES'),
       (20, 'ACT 5 — PHOTONS INTERACT WITH ATOMS'), (25, 'ACT 6 — RADIATION BECOMES DATA'), (30, 'ACT 7 — MEASUREMENTS BECOME IMAGES'), (35, 'ACT 8 — IDENTIFY THE ANEURYSM'),
       (40, 'ACT 9 — WHAT THIS MEANS FOR THE PATIENT')]
MUSIC = [(0, 20, 'curiosity: the hook on bell and glass from the first beat, light drums, the build into the gantry'),
         (20, 40, 'the tube\'s techno groove (pulse bass, stabs, pluck hook); held breath, then the high-voltage drop at 32.5 s; riser and roll into the dive'),
         (40, 60, 'bullet time in half time with a wobble bass; the bremsstrahlung chime at 44.4 s; the drive with reese bass and the lead hook; the music itself filtered during S14'),
         (60, 80, 'flow: groove with heartbeat kicks, glass hook, the fill motif; held breath and the acquisition trigger at 78.5 s'),
         (80, 100, 'the dive riser, a breakdown on the iodine atom, silence, the drop on photoelectric absorption at 88.0 s'),
         (100, 120, 'ordered conversion: data arps in 16ths, the bell hook, the bit ladder of the converter, riser'),
         (120, 140, 'the reconstruction build (machine knocks, rising hits per doubling of views), held breath, the main drop on the grayscale image at 132 s'),
         (140, 160, 'discovery: clean four-on-the-floor, glass and pluck hooks; held breath, the climax on the reviewer\'s click at 154 s'),
         (160, 180, 'calm: pads and bell; a two-beat pause at 168 s; a warm phrase; the A-major turnaround that lands on the opening hit')]
music_at = lambda t: next(m for a, b, m in MUSIC if a <= t < b)
BASE = ("Strict flat 2D 16-bit pixel-art scientific animation frame. Vertical 9:16, designed on a 360x640 pixel grid. Crisp square pixels, "
        "hard edges, discrete shading, limited palette, deep navy background. Clear medical and physical relationships. Consistent anatomy, "
        "equipment and particle identities. Strong silhouettes, readable at phone size. Generous space for separately added labels. Ivory "
        "equipment, cyan electrons, magenta nuclei, yellow X-ray symbols, green scintillation-light symbols, violet illustrative contrast "
        "molecules. Use grayscale for clinical CT image panels. Use amber only for editorial highlights. No embedded text. No brand logos. "
        "No photorealism. No 3D rendering. No anti-aliasing. No motion blur. No gore. No random sci-fi effects.")

sb = ['# Storyboard — 45 scenes × 4 s = 180 s', '', 'Generated by `tools/make_docs.py` from `镜头表.md`, the scene files and the cue sheet. Times are film seconds; '
      'one scene is 2 bars at 120 BPM. "In" says how the scene joins the previous one: a dithered dissolve of the given length, or a cut.', '']
tl = ['# Editing timeline', '', 'The film is assembled by the engine in one pass (no external editor): `engine/film.js` lists the 45 scenes, each exactly 4.000 s; '
      'a scene with `xin` dissolves in from the previous scene\'s last frame with an ordered dither. Text is the editor layer (`engine/lib/cap.js`), '
      'off in the textless version (`?notext=1`). Audio is one stereo mix (`tools/synth_audio.py`) laid on the picture from frame 0.', '',
      '| # | In | Out | Scene | Transition in | Camera | Label (AZ) | Music |', '|---|---|---|---|---|---|---|---|']
pr = ['# Keyframe prompts (one per scene)', '', 'The film itself is drawn by code, not generated; these prompts are the reusable keyframe brief of the master prompt '
      '(§09) applied to every scene, for anyone who wants to make alternative keyframes or a storyboard print. Base prompt:', '', '> ' + BASE, '']
cap = ['# Caption list (Azerbaijani context labels)', '', 'One short label per scene (typed on at 60 characters/s, held at least 17 characters/s + 0.3 s), plus part labels next to '
       'the thing they name. Times are film seconds (shown on screen from → until, before the 0.25 s fade). The textless version shows none of them.', '',
       '| # | Time | Label | English gloss | Part labels |', '|---|---|---|---|---|']
act_i = 0
for i, (sid, row) in enumerate(zip(ids, SHOTS)):
    n = i + 1; t0 = i * 4.0; key = f'S{n:02d}'
    while act_i < len(ACT) and ACT[act_i][0] == i: sb += ['', f'## {ACT[act_i][1]}', '']; act_i += 1
    _, span, obj, act, camw, label, how = row[:7]
    lab = LABELS.get(key, [key, label, '', ''])
    x = xin(sid); trans = f'dither dissolve {x:.2f} s' if x else 'cut'
    cs = by_scene.get(sid, [])
    sb += [f'### {key} · {span} · `{sid}`', '', f'- **Picture:** {obj}.', f'- **Action:** {act}.', f'- **Camera:** {camw} ({CAM.get(camw, camw)}).', f'- **In:** {trans}.',
           f'- **Label:** {lab[1]} — *{lab[2]}*' + (f'; part labels: {lab[3]}' if lab[3] not in ('—', '') else '') + '.',
           f'- **Motion and science notes:** {header(sid)}',
           f'- **Sound:** ' + ', '.join(f"{c['sfx']} @{c['t'] - t0:.2f}" for c in cs if c['sfx'] != 'type') + f'. Music: {music_at(t0)}.', '']
    tl.append(f'| {n} | {t0:06.2f} | {t0 + 4:06.2f} | `{sid}` | {trans} | {camw} {CAM.get(camw, "")} | {lab[1]} | {music_at(t0).split(":")[0].split(";")[0]} |')
    pr += [f'## {key} · {span}', '', f'{BASE} Scene: {obj}; {act}. Camera: {CAM.get(camw, camw)}.', '']
    tlog = textlog.get(sid, [])
    ctx = next((e for e in tlog if e.get('kind') == 'ctx'), None)
    tt = f"{t0 + ctx['t0']:.2f}–{t0 + ctx['t1']:.2f}" if ctx else f'{t0:.2f}–{t0 + 4:.2f}'
    cap.append(f'| {n} | {tt} | {lab[1]} | {lab[2]} | {lab[3]} |')
(D / 'storyboard.md').write_text('\n'.join(sb) + '\n')
(D / 'timeline.md').write_text('\n'.join(tl) + '\n\nOpening and closing frames: `docs/frame_open.png` (0.000 s) and `docs/frame_close.png` (179.983 s) are the same composition; '
                               'the music\'s last bar is the A-major turnaround into the opening hit, and the mix\'s ringing tail is folded back onto its start, so the file loops.\n')
(D / 'prompts.md').write_text('\n'.join(pr) + '\n')
(D / 'captions.md').write_text('\n'.join(cap) + '\n')
# cue sheet
cs = ['# Music and sound-effect cue sheet', '', 'Every sound effect comes from a cue the picture emits (`window.dumpCues()` in `engine/film.js`), so it lands on its visual '
      'cause. Soft interface sounds are snapped to the nearest 16th note when they are within 45 ms of it; physical events (emission, absorption, the reveal) '
      'stay exact. Tonal effects take their notes from the chord sounding at that moment. `type` and `tag` (the labels) are left out of the textless mix.', '',
      '## Music arc', '', '| From | To | Section |', '|---|---|---|'] + [f'| {a:.0f} s | {b:.0f} s | {m} |' for a, b, m in MUSIC] + \
     ['', 'Harmony: D minor, the loop Dm – Bb – F – C (one chord per bar) for bars 1–80; bars 81–90: Bb – C – Dm – Dm – Bb – C – F – F – Bb – A, the A major leading back to Dm at the loop. '
      'The hook (2 bars): a 3-3-2 bar A9–D–F · E–D–C and its answer D–F–A · G–F–E, one melody that sits on every chord of the loop.', '',
      '## Cues', '', '| Time (s) | Scene | Effect | Gain | Pan | Arg |', '|---|---|---|---|---|---|']
for c in cues['cues']: cs.append(f"| {c['t']:.3f} | {c['scene']} | {c['sfx']} | {c['g']} | {c['pan']} | {'' if c['arg'] is None else c['arg']} |")
(D / 'cue_sheet.md').write_text('\n'.join(cs) + '\n')
print('docs ->', D, [p.name for p in sorted(D.glob('*.md'))])
