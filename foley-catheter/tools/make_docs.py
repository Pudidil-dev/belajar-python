#!/usr/bin/env python3
"""Build the text documents of the production package from the film's own sources (镜头表.md, the scene files' header
comments, build/cues.json and build/textlog.json from render.py --cues), so they cannot drift from the film:
docs/storyboard.md, docs/timeline.md, docs/prompts.md, docs/labels.md, docs/labels.srt, docs/labels.json, docs/cue_sheet.md.

  python3 tools/make_docs.py
"""
import json, re
from collections import defaultdict
from pathlib import Path
R = Path(__file__).resolve().parent.parent
D = R / 'docs'; D.mkdir(exist_ok=True)
shot = (R / '镜头表.md').read_text()
cues = json.loads((R / 'build/cues.json').read_text())
textlog = json.loads((R / 'build/textlog.json').read_text())
def table(md, first):
    rows, on = [], False
    for ln in md.splitlines():
        if ln.startswith('| ' + first): on = True; continue
        if on and ln.startswith('|---'): continue
        if on and ln.startswith('|'): rows.append([c.strip() for c in ln.strip().strip('|').split('|')])
        elif on: break
    return rows
SHOTS = table(shot, '场 | 时间段')
CAM = {'停': 'hold', '缓推': 'slow push', '拉远': 'pull out', '横移': 'track / pan / orbit', '快推': 'fast push (accent)', '切': 'cut'}
ids = re.findall(r"'(s\d\d_[a-z0-9]+)'", (R / 'engine/film.js').read_text())
def header(sid):
    out = []
    for ln in (R / 'engine/scenes' / f'{sid}.js').read_text().splitlines():
        if ln.startswith('//'): out.append(ln[2:].strip())
        else: break
    return ' '.join(out)
def xin(sid):
    m = re.search(r'xin:\s*([\d.]+)', (R / 'engine/scenes' / f'{sid}.js').read_text()); return float(m.group(1)) if m else 0.0
by = defaultdict(list)
for c in cues['cues']: by[c['scene']].append(c)
MUSIC = [(0, 9, 'curiosity and the destination: the opening motif on bell, the reveal chime on the balloon (6.4 s)'), (9, 18, 'retention and the bedside: a soft pulse, pads open'),
         (18, 33, 'the second question (18.5 s), the eye, the channels: light groove, glass arps, a held breath before the cross-section (30 s)'),
         (33, 48, 'ports, tubing, the bag: steady; the completion tone on the bag (47 s)'), (48, 60, 'recap and answer: the opening motif returns (54 s); the last bar leads into the first')]
music_at = lambda t: next(m for a, b, m in MUSIC if a <= t < b)
BASE = ("Premium cinematic 3D voxel and pixel-art medical illustration, vertical 9:16, dark navy background. Anatomically coherent adult male sagittal "
        "pelvic cutaway with a representative two-way Foley urinary catheter. Controlled voxel detail, clean clinical lighting, muted rose tissue, ivory "
        "catheter material, pale-yellow urine, translucent retention balloon. Readable silhouettes and clear lumen boundaries. Professional, clinical, "
        "nonsexual presentation. Consistent anatomy and device geometry. Space for labels added separately in editing. No embedded text, no brand logos, "
        "no gore, no exaggerated anatomy, no toy-like styling, no floating device parts, no excessive bloom.")
MOTION = ("Animate only the specified medical action. Preserve: anatomical route, catheter shape, drainage-eye positions, balloon location, lumen "
          "separation, external connection topology. Use gentle fluid movement and controlled camera motion. Moving markers show direction only. Keep "
          "the balloon stable during drainage. No spontaneous inflation, new openings, shape morphing, reverse flow or forceful device movement.")
sb = ['# Storyboard — 20 scenes × 3 s = 60 s', '', 'Generated by `tools/make_docs.py` from `镜头表.md`, the scene files and the cue sheet. Each scene\'s "motion" paragraph is the '
      'header comment of its scene file, i.e. what the code actually animates.', '']
tl = ['# Editing timeline (exactly 60.000 s, 60 fps)', '', 'The engine assembles the film in one pass (`engine/film.js`): 20 scenes of 3.000 s; a scene with an "in" value '
      'dissolves from the previous scene\'s last frame with an ordered dither. Labels are the editor layer (`engine/lib/cap.js`), absent from the clean '
      'version (`--notext`), and listed with times in `docs/labels.srt` for re-editing. Audio: `music.wav`, `sfx.wav`, `mix.wav` from `tools/synth_audio.py`.', '',
      '| # | In (s) | Out (s) | Scene | Transition in | Camera | Label | Music |', '|---|---|---|---|---|---|---|---|']
pr = ['# Keyframe and motion prompts (one per scene)', '', 'The film is drawn by code; these are the master prompt\'s §08 image base and §10 motion base applied to every '
      'scene, for alternative keyframes or a print storyboard.', '', '**Image base:** ' + BASE, '', '**Motion base:** ' + MOTION, '']
for i, (sid, row) in enumerate(zip(ids, SHOTS)):
    n = i + 1; t0 = i * 3.0; key = f'S{n:02d}'
    _, span, obj, act, camw, label, how = row[:7]
    x = xin(sid); trans = f'dissolve {x:.2f} s' if x else 'cut'
    snd = ', '.join(f"{c['sfx']} @{c['t'] - t0:.2f}" for c in by.get(sid, []) if c['sfx'] != 'type')
    sb += [f'## {key} · {span} · `{sid}`', '', f'- **Picture:** {obj}.', f'- **Action:** {act}.', f'- **Camera:** {camw} ({CAM.get(camw, camw)}).', f'- **In:** {trans}.',
           f'- **Label:** {label}.', f'- **Motion (from the code):** {header(sid)}', f'- **Sound:** {snd}. Music: {music_at(t0)}.', '']
    tl.append(f'| {n} | {t0:05.2f} | {t0 + 3:05.2f} | `{sid}` | {trans} | {CAM.get(camw, camw)} | {label} | {music_at(t0).split(":")[0]} |')
    pr += [f'## {key} · {span}', '', f'**Image:** {BASE} Scene: {obj}; {act}.', '', f'**Motion:** {MOTION} This scene: {act}. Camera: {CAM.get(camw, camw)}.', '']
(D / 'storyboard.md').write_text('\n'.join(sb) + '\n')
(D / 'timeline.md').write_text('\n'.join(tl) + '\n\nLoop: S20 ends pushed into a catheter segment in the penile urethra (scale 16 px/mm); S01 starts on that exact frame and pulls back '
                               '(`docs/frame_close.png` = `docs/frame_open.png`). The opening question returns 0.3 s after the loop point.\n')
(D / 'prompts.md').write_text('\n'.join(pr) + '\n')
# labels: list, SRT and JSON (film times; every label in the film, with its scene and kind)
labs = []
for i, sid in enumerate(ids):
    for e in textlog.get(sid, []):
        labs.append({'scene': sid, 'kind': e['kind'], 'text': e['text'], 'start': round(i * 3 + e['t0'], 3), 'end': round(i * 3 + min(3.0, (e['t1'] or 3) + 0.25), 3)})
(D / 'labels.json').write_text(json.dumps(labs, indent=1, ensure_ascii=False) + '\n')
def ts(x): h_ = int(x // 3600); m = int(x % 3600 // 60); s = x % 60; return f'{h_:02d}:{m:02d}:{int(s):02d},{int(round((s - int(s)) * 1000)):03d}'
(D / 'labels.srt').write_text('\n'.join(f"{k + 1}\n{ts(l['start'])} --> {ts(l['end'])}\n{l['text']}\n" for k, l in enumerate(labs)))
(D / 'labels.md').write_text('# Editable label list\n\nThe labeled version draws these with the film\'s pixel font; the clean version has none. The same list is in '
                             '`labels.srt` (for CapCut, Premiere, DaVinci …) and `labels.json`. Times are film seconds (typing starts → fade ends).\n\n'
                             '| Scene | Kind | Text | Start | End |\n|---|---|---|---|---|\n' + '\n'.join(f"| {l['scene']} | {l['kind']} | {l['text']} | {l['start']:.2f} | {l['end']:.2f} |" for l in labs) + '\n')
cs = ['# Music and SFX cue sheet', '', 'Every effect comes from a cue the picture emits (`window.dumpCues()`), so it lands on its visual cause; soft interface '
      'sounds snap to the 16th grid when within 45 ms. Label sounds (`type`, `tag`) are left out of the *_notext stems.', '', '## Music', '',
      '| From | To | Section |', '|---|---|---|'] + [f'| {a} s | {b} s | {m} |' for a, b, m in MUSIC] + \
     ['', 'One chord per 3-s scene (Fmaj7 – Am7 – Cmaj7 – G6, looping); the 300 Hz – 3 kHz band is thinned in the music so a voice-over sits on top. '
      'Mix at −16 LUFS integrated, peak ≤ −1 dBFS.', '', '## Cues', '', '| Time (s) | Scene | Effect | Gain | Pan | Arg |', '|---|---|---|---|---|---|'] + \
     [f"| {c['t']:.3f} | {c['scene']} | {c['sfx']} | {c['g']} | {c['pan']} | {'' if c['arg'] is None else c['arg']} |" for c in cues['cues']]
(D / 'cue_sheet.md').write_text('\n'.join(cs) + '\n')
print('docs ->', sorted(p.name for p in D.iterdir()))
